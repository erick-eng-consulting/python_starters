
# una lista de nombres de frutas.

mi_lista_de_frutas = []

# agregar una nueva fruta
# la función append

# para ver como esta el contenido antes de agregar
print(mi_lista_de_frutas)

mi_lista_de_frutas.append("MANZANA")

# para ver como esta el contenido despues de aplicar
print(mi_lista_de_frutas)

# para insertar
mi_lista_de_frutas.insert(0, "pera")

print(mi_lista_de_frutas)

# para remover
mi_lista_de_frutas.remove("MANZANA")

print(mi_lista_de_frutas)

# eliminar por posicion
mi_lista_de_frutas.pop(-1)


